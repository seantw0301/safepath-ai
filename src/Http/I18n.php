    private static ?int $lang = null;

    public static function lang(): string
    {
        return self::index() === 1 ? 'zh-Hant' : 'en';
    }

    public static function isZh(): bool
    {
        return self::index() === 1;
    }

    public static function t(string $key): string
    {
        return self::TEXT[$key][self::index()] ?? $key;
    }

    private static function index(): int
    {
        if (self::$lang === null) {
            $wanted = $_GET['lang'] ?? $_COOKIE['lang'] ?? 'en';
            self::$lang = $wanted === 'zh' ? 1 : 0;
            if (isset($_GET['lang']) && !headers_sent()) {
                setcookie('lang', self::$lang === 1 ? 'zh' : 'en', ['expires' => time() + 86400 * 30, 'path' => '/', 'samesite' => 'Lax']);
            }
        }
        return self::$lang;
    }
